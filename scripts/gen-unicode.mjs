#!/usr/bin/env node
// Writes cpp/core/src/unicode_tables.cpp from the Unicode Character Database files under scripts/unicode/<version>.
import { readFileSync, writeFileSync } from 'node:fs';
import { dirname, join } from 'node:path';
import { fileURLToPath } from 'node:url';

const VERSION = '16.0.0';
const root = join(dirname(fileURLToPath(import.meta.url)), '..');
const ucd = join(root, 'scripts', 'unicode', VERSION);
const out = join(root, 'cpp', 'core', 'src', 'unicode_tables.cpp');

const GCB = [
  'Other',
  'CR',
  'LF',
  'Control',
  'Extend',
  'ZWJ',
  'Regional_Indicator',
  'Prepend',
  'SpacingMark',
  'L',
  'V',
  'T',
  'LV',
  'LVT',
];
const INCB = ['None', 'Linker', 'Consonant', 'Extend'];

function index(names, name) {
  const value = names.indexOf(name);
  if (value <= 0) throw new Error(`unknown property value ${name}`);
  return value;
}

// Sorted, merged [first, last, value] ranges over the data lines pick maps to a value.
function ranges(file, pick) {
  const found = [];
  for (const raw of readFileSync(join(ucd, file), 'utf8').split('\n')) {
    const line = raw.split('#')[0].trim();
    if (!line) continue;
    const fields = line.split(';').map((f) => f.trim());
    const value = pick(fields);
    if (value === undefined) continue;
    const [a, b] = fields[0].split('..');
    found.push([Number.parseInt(a, 16), Number.parseInt(b ?? a, 16), value]);
  }
  found.sort((x, y) => x[0] - y[0]);
  const merged = [];
  for (const r of found) {
    const last = merged[merged.length - 1];
    if (last && r[0] <= last[1])
      throw new Error(`${file}: overlapping ranges at ${r[0].toString(16)}`);
    if (last && last[2] === r[2] && last[1] + 1 === r[0]) last[1] = r[1];
    else merged.push([...r]);
  }
  return merged;
}

const hex = (n) => `0x${n.toString(16).toUpperCase().padStart(4, '0')}`;

function table(name, rows) {
  return [
    `extern const Range ${name}[] = {`,
    ...rows.map(([a, b, v]) => `    {${hex(a)}, ${hex(b)}, ${v}},`),
    '};',
    `extern const uint32_t ${name}Count = ${rows.length};`,
    '',
  ].join('\n');
}

const gcb = ranges('GraphemeBreakProperty.txt', (f) => index(GCB, f[1]));
const pict = ranges('emoji-data.txt', (f) => (f[1] === 'Extended_Pictographic' ? 1 : undefined));
const incb = ranges('DerivedCoreProperties.txt', (f) =>
  f[1] === 'InCB' ? index(INCB, f[2]) : undefined,
);
const space = ranges('PropList.txt', (f) => (f[1] === 'White_Space' ? 1 : undefined));

const source = [
  `// Generated by scripts/gen-unicode.mjs from Unicode ${VERSION}. Run yarn gen:unicode, do not edit.`,
  '#include "unicode.hpp"',
  '',
  'namespace codepad::unicode {',
  '',
  table('kGraphemeBreak', gcb),
  table('kExtendedPictographic', pict),
  table('kIndicConjunctBreak', incb),
  table('kWhiteSpace', space),
  '}  // namespace codepad::unicode',
  '',
].join('\n');

writeFileSync(out, source);
console.log(
  `unicode ${VERSION}: ${gcb.length} break, ${pict.length} pictographic, ${incb.length} conjunct, ${space.length} space ranges`,
);

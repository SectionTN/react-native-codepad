import { existsSync, mkdirSync, readdirSync, readFileSync, statSync, writeFileSync } from 'node:fs';
import path from 'node:path';

const HEADER = 'host/include/host_grammars.h';

/** The language symbol of a generated parser.c, the rule scripts/build-host-treesitter.sh uses. */
export function languageSymbol(parserC: string): string | null {
  const m = /TSLanguage \*tree_sitter_([a-z0-9_]+)\(void\)/.exec(parserC);
  return m?.[1] ?? null;
}

function parserFiles(dir: string, out: string[]): void {
  for (const name of readdirSync(dir).sort()) {
    if (name.startsWith('.') || name === 'node_modules') continue;
    const file = path.join(dir, name);
    if (statSync(file).isDirectory()) parserFiles(file, out);
    else if (name === 'parser.c' && path.basename(dir) === 'src') out.push(file);
  }
}

/** Every grammar name under languagesDir, read from the parser.c files outside the cache, sorted. */
export function hostGrammarNames(languagesDir: string): string[] {
  const files: string[] = [];
  for (const id of readdirSync(languagesDir).sort()) {
    const grammar = path.join(languagesDir, id, 'grammar');
    if (id.startsWith('.') || !existsSync(grammar) || !statSync(grammar).isDirectory()) continue;
    parserFiles(grammar, files);
  }
  const names = files.map((file) => {
    const symbol = languageSymbol(readFileSync(file, 'utf8'));
    if (!symbol) throw new Error(`cannot find the language symbol in ${file}`);
    return symbol;
  });
  return [...new Set(names)].sort();
}

/** The header the Swift package links the host grammars through, one declaration per grammar. */
export function hostHeader(names: string[]): string {
  const decls = [...names].sort().map((n) => `const void *tree_sitter_${n}(void);`);
  return [
    '#ifndef CODEPAD_HOST_GRAMMARS_H',
    '#define CODEPAD_HOST_GRAMMARS_H',
    '',
    '// Generated by yarn gen:languages: the grammar entry points swift test links. Do not edit by hand.',
    ...decls,
    '',
    '#endif',
    '',
  ].join('\n');
}

export function writeHostHeader(languagesDir: string): void {
  const file = path.join(languagesDir, HEADER);
  const text = hostHeader(hostGrammarNames(languagesDir));
  if (existsSync(file) && readFileSync(file, 'utf8') === text) return;
  mkdirSync(path.dirname(file), { recursive: true });
  writeFileSync(file, text);
}
